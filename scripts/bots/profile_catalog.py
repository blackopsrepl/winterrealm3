def buff(key, skill_id, priority, recipients, blocking_effects):
	"""Declare one exact-caster buff with explicit exact recipients."""
	return {
		"key": key,
		"skill_id": skill_id,
		"priority": priority,
		"recipients": tuple(recipients),
		"blocking_effects": tuple(blocking_effects),
	}


